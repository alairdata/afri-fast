-- Every recipe "Build a recipe from my kitchen" generates (2026-10-29), saved or not, written by the server
-- (api/gemini.js build_recipe) with the service key. For the owner's own analysis: RLS on with no policies, so the
-- app's public key can neither read nor write it. Safe to run more than once.
CREATE TABLE IF NOT EXISTS generated_recipes (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      UUID REFERENCES auth.users(id) ON DELETE CASCADE, -- null only for a call without a valid sign-in
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  input_text   TEXT,        -- what they typed or said they have
  had_photo    BOOLEAN NOT NULL DEFAULT false,
  budget_kcal  INTEGER,     -- calories per person they asked for
  servings     INTEGER,
  country      TEXT,
  title        TEXT,
  description  TEXT,
  minutes      INTEGER,
  used_count   INTEGER,
  total_count  INTEGER,
  total_kcal   INTEGER,     -- per person, as built
  foods        JSONB,       -- ingredients: per-100 g nutrition, grams per person, measures
  method       JSONB,       -- the steps, amounts filled in for the whole pot
  tip          TEXT
);
CREATE INDEX IF NOT EXISTS idx_generated_recipes_user_id ON generated_recipes(user_id);
CREATE INDEX IF NOT EXISTS idx_generated_recipes_created_at ON generated_recipes(created_at);
ALTER TABLE generated_recipes ENABLE ROW LEVEL SECURITY;
