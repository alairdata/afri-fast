-- One row per (user, day the prediction was computed) -- holds that day's forward-looking
-- Burnout Likelihood guesses (today through 3 days out) plus the parameters that produced them,
-- mirroring weight_predictions. Past days in the Burnout chart are already covered by
-- burnout_daily_scores (frozen once finalized, see burnoutHistory.js) -- this table is only the
-- forecast half, so predicted-vs-actual can be checked later once those days become "past" and get
-- their own frozen score.
CREATE TABLE IF NOT EXISTS burnout_predictions (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id            UUID        NOT NULL,
  date               TEXT        NOT NULL, -- toDateString(), the day this snapshot was computed
  predictions        JSONB       NOT NULL, -- [{ targetDate, daysOut, score, deficitPts, volatilityPts, proteinPts, waterPts, carbsPts, fiberPts, fatPts, avgCalories, avgProtein, avgCarbs, avgFats, avgFiber, avgWaterMl }, ...] for today (daysOut 0) through 3 days out
  bmr                NUMERIC,
  tdee               NUMERIC,
  pace_preference    TEXT,
  daily_calorie_goal NUMERIC,
  protein_goal       NUMERIC,
  carbs_goal         NUMERIC,
  fats_goal          NUMERIC,
  weight_kg          NUMERIC,
  days_to_crash      INTEGER,             -- headline "estimated crash risk window" at save time
  crash_date         TEXT,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (user_id, date)
);

CREATE INDEX IF NOT EXISTS idx_burnout_predictions_user_id ON burnout_predictions(user_id);
