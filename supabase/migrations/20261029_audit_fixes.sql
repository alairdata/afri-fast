-- Data audit fixes (2026-10-29). Safe to run more than once.

-- 1. burnout_predictions was never created (20260830_add_burnout_predictions.sql didn't run), so the
--    Progress tab's daily Burnout forecast snapshot has been failing silently.
CREATE TABLE IF NOT EXISTS burnout_predictions (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id            UUID        NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  date               TEXT        NOT NULL,
  predictions        JSONB       NOT NULL,
  bmr                NUMERIC,
  tdee               NUMERIC,
  pace_preference    TEXT,
  daily_calorie_goal NUMERIC,
  protein_goal       NUMERIC,
  carbs_goal         NUMERIC,
  fats_goal          NUMERIC,
  weight_kg          NUMERIC,
  days_to_crash      INTEGER,
  crash_date         TEXT,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (user_id, date)
);
CREATE INDEX IF NOT EXISTS idx_burnout_predictions_user_id ON burnout_predictions(user_id);
ALTER TABLE burnout_predictions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "own burnout predictions" ON burnout_predictions;
CREATE POLICY "own burnout predictions" ON burnout_predictions
  FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

-- 2. active_fasts had own-row policies but RLS was off, so the policies did nothing.
ALTER TABLE active_fasts ENABLE ROW LEVEL SECURITY;

-- 3. chat_messages (people's chats) was readable and writable by anyone with the app's public key.
--    Only api/chat.js writes it, with the service key, which bypasses RLS; the app never reads it.
ALTER TABLE chat_messages ENABLE ROW LEVEL SECURITY;

-- 4. Community photos: this open policy let anyone (even signed out) insert a photo under any user_id.
--    "Users share their own community photos" already covers real sharing.
DROP POLICY IF EXISTS "Anyone can insert community photos" ON recipe_community_photos;

-- 5. Clear History deletes the person's ledger and burnout scores, but there was no delete policy,
--    so those rows quietly stayed.
DROP POLICY IF EXISTS "Users can delete their own goal ledger" ON daily_goal_ledger;
CREATE POLICY "Users can delete their own goal ledger" ON daily_goal_ledger
  FOR DELETE USING (auth.uid() = user_id);
DROP POLICY IF EXISTS "Users can delete own burnout scores" ON burnout_daily_scores;
CREATE POLICY "Users can delete own burnout scores" ON burnout_daily_scores
  FOR DELETE USING (auth.uid() = user_id);
