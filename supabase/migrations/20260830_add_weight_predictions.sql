-- One row per (user, day the prediction was computed) -- holds that day's whole Sun-Sat
-- prediction line plus the parameters that produced it, so predicted-vs-actual accuracy can be
-- checked later once real weigh-ins land on the target dates. Upserted on user_id+date, so it
-- always reflects the latest computation made that day; once the date rolls over, the previous
-- day's row stops being touched and becomes the historical record of what was predicted.
CREATE TABLE IF NOT EXISTS weight_predictions (
  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id                UUID        NOT NULL,
  date                   TEXT        NOT NULL, -- toDateString(), the day this snapshot was computed
  predictions            JSONB       NOT NULL, -- [{ targetDate, daysOut, predictedKg, marginKg }, ...]
  anchor_weight_kg       NUMERIC,              -- today's EWMA weight (or raw current weight) used as the projection's start point
  daily_rate_kg          NUMERIC,              -- kg/day rate the line was extrapolated at
  confidence             NUMERIC,              -- 0-1, logging-streak/recency-based confidence used for the margin
  days_since_weigh_in    INTEGER,
  tdee                   NUMERIC,
  bmr                    NUMERIC,
  pace_preference        TEXT,                 -- 'slow' | 'moderate' | 'aggressive' | 'extreme' | null
  avg_daily_deficit_kcal NUMERIC,              -- weeklyPace.dBar, the logged-calorie-driven deficit the rate came from
  pace_ratio             NUMERIC,              -- weeklyPace.pRatio, actual deficit vs the chosen pace's target deficit
  badge_label            TEXT,                 -- 'On Pace' | 'Off Pace' | 'Stalled' | 'Too Aggressive' | etc, at save time
  created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (user_id, date)
);

CREATE INDEX IF NOT EXISTS idx_weight_predictions_user_id ON weight_predictions(user_id);
