-- Admin portal actions (2026-10-29), after 20261029_admin_portal.sql. Safe to run more than once.

-- 1. Flag and restrict a user. A flag is a private marker for admins. Restricted people can't use Logga: the app
--    shows them a "your account is restricted" screen and the AI endpoints refuse them. They can read their own
--    row (that's how the app knows); only admins can change it.
CREATE TABLE IF NOT EXISTS user_admin_flags (
  user_id    UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  flagged    BOOLEAN NOT NULL DEFAULT false,
  restricted BOOLEAN NOT NULL DEFAULT false,
  note       TEXT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE user_admin_flags ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "own flags readable" ON user_admin_flags;
CREATE POLICY "own flags readable" ON user_admin_flags FOR SELECT USING (auth.uid() = user_id OR is_admin());
DROP POLICY IF EXISTS "admins manage flags" ON user_admin_flags;
CREATE POLICY "admins manage flags" ON user_admin_flags FOR ALL TO authenticated USING (is_admin()) WITH CHECK (is_admin());

-- 2. Nudges sent from the portal. The app picks up undelivered ones when it opens (into the bell inbox, shown as a
--    notification) and marks them delivered; phones with a push address also get a real push straight away.
CREATE TABLE IF NOT EXISTS user_nudges (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  title        TEXT NOT NULL,
  body         TEXT NOT NULL,
  sent_by      TEXT,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  delivered_at TIMESTAMPTZ,
  pushed       BOOLEAN NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS idx_user_nudges_user ON user_nudges(user_id, delivered_at);
ALTER TABLE user_nudges ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "own nudges" ON user_nudges;
CREATE POLICY "own nudges" ON user_nudges FOR SELECT USING (auth.uid() = user_id OR is_admin());
DROP POLICY IF EXISTS "own nudges delivered" ON user_nudges;
CREATE POLICY "own nudges delivered" ON user_nudges FOR UPDATE USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
DROP POLICY IF EXISTS "admins send nudges" ON user_nudges;
CREATE POLICY "admins send nudges" ON user_nudges FOR INSERT TO authenticated WITH CHECK (is_admin());

-- 3. Portal settings (for now: whether the Android app is live).
CREATE TABLE IF NOT EXISTS admin_settings (
  key        TEXT PRIMARY KEY,
  value      JSONB,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE admin_settings ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "admins manage settings" ON admin_settings;
CREATE POLICY "admins manage settings" ON admin_settings FOR ALL TO authenticated USING (is_admin()) WITH CHECK (is_admin());
